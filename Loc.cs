    private static readonly string SettingsPath = Path.Combine(TranscriptService.AppDir, "settings.ini");

    public static string Current { get; private set; } = DetectDefault();

    public static event Action? Changed;

    public static void Set(string code)
    {
        if (code == Current || !Strings.ContainsKey(code)) return;
        Current = code;
        Save();
        Changed?.Invoke();
    }

    public static string T(string key) =>
        Strings[Current].TryGetValue(key, out var s) ? s
        : Strings["en"].TryGetValue(key, out var en) ? en
        : key;

    public static string T(string key, params object[] args) => string.Format(T(key), args);

    private static string DetectDefault()
    {
        try
        {
            if (File.Exists(SettingsPath))
            {
                foreach (var line in File.ReadAllLines(SettingsPath))
                {
                    var parts = line.Split('=', 2);
                    if (parts.Length == 2 && parts[0].Trim() == "ui" && Strings.ContainsKey(parts[1].Trim()))
                        return parts[1].Trim();
                }
            }
        }
        catch { /* fall back to the OS language */ }

        return CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "sl" ? "sl" : "en";
    }

    private static void Save()
    {
        try
        {
            Directory.CreateDirectory(TranscriptService.AppDir);
            File.WriteAllText(SettingsPath, $"ui={Current}{Environment.NewLine}");
        }
        catch { /* not critical */ }
    }

