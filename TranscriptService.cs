using System.Diagnostics;
using System.Text;
using System.Text.RegularExpressions;
using Whisper.net;
using YoutubeExplode;
using YoutubeExplode.Videos;
using YoutubeExplode.Videos.ClosedCaptions;
using YoutubeExplode.Videos.Streams;

namespace YtTranscript;

public record TranscriptOptions(string Url, string Language, string Model, bool ForceWhisper);
public record TranscriptResult(string Title, string Text, string Source);
public record ProgressInfo(string Status, double? Percent, string? PartialText = null);

public sealed class TranscriptService
{
    public static readonly string AppDir = InitAppDir();

    private static string InitAppDir()
    {
        var root = Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData);
        var dir = Path.Combine(root, "YtTranscript");
        var legacy = Path.Combine(root, "YtPrepis"); // name used before v1.1.1
        try
        {
            if (!Directory.Exists(dir) && Directory.Exists(legacy)) Directory.Move(legacy, dir);
        }
        catch { /* keep going with a fresh folder */ }
        return dir;
    }

    private static readonly HttpClient Http = new() { Timeout = Timeout.InfiniteTimeSpan };
    private static readonly TimeSpan ParagraphGap = TimeSpan.FromSeconds(2);

    private readonly YoutubeClient _yt = new();

    public async Task<TranscriptResult> RunAsync(TranscriptOptions o, IProgress<ProgressInfo> p, CancellationToken ct)
    {
        var id = VideoId.TryParse(o.Url.Trim())
                 ?? throw new ArgumentException(L.T("InvalidUrl"));

        p.Report(new(L.T("ReadingVideo"), null));
        var video = await _yt.Videos.GetAsync(id, ct);

        if (!o.ForceWhisper)
        {
            p.Report(new(L.T("LookingForCaptions"), null));
            var captions = await TryCaptionsAsync(id, o.Language, ct);
            if (captions is not null)
                return new(video.Title, captions.Value.Text, captions.Value.Source);
        }

        var text = await WhisperAsync(id, o, p, ct);
        return new(video.Title, text, $"Whisper ({o.Model})");
    }

    // ---------- 1) YouTube captions ----------

    private async Task<(string Text, string Source)?> TryCaptionsAsync(VideoId id, string lang, CancellationToken ct)
    {
        ClosedCaptionManifest manifest;
        try { manifest = await _yt.Videos.ClosedCaptions.GetManifestAsync(id, ct); }
        catch (Exception ex) when (ex is not OperationCanceledException) { return null; }

        IEnumerable<ClosedCaptionTrackInfo> candidates = manifest.Tracks;
        if (lang != "auto")
            candidates = candidates.Where(t => t.Language.Code.StartsWith(lang, StringComparison.OrdinalIgnoreCase));

        // manually created captions take priority over auto-generated ones
        var info = candidates.OrderBy(t => t.IsAutoGenerated).FirstOrDefault();
        if (info is null) return null;

        var track = await _yt.Videos.ClosedCaptions.GetAsync(info, ct);
        var segments = track.Captions
            .Where(c => !string.IsNullOrWhiteSpace(c.Text))
            .Select(c => (c.Offset, c.Offset + c.Duration, c.Text))
            .ToList();
        if (segments.Count == 0) return null;

        var source = L.T("CaptionsSource", info.Language.Name) + (info.IsAutoGenerated ? L.T("AutoGenerated") : "");
        return (FormatParagraphs(segments), source);
    }

    // ---------- 2) Whisper ----------

    private async Task<string> WhisperAsync(VideoId id, TranscriptOptions o, IProgress<ProgressInfo> p, CancellationToken ct)
    {
        var modelPath = await EnsureModelAsync(o.Model, p, ct);

        var tmp = Path.Combine(Path.GetTempPath(), "YtTranscript_" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(tmp);
        try
        {
            p.Report(new(L.T("DownloadingAudio"), 0));
            var manifest = await _yt.Videos.Streams.GetManifestAsync(id, ct);
            var audio = manifest.GetAudioOnlyStreams().Where(s => s.Container == Container.Mp4).TryGetWithHighestBitrate()
                        ?? manifest.GetAudioOnlyStreams().TryGetWithHighestBitrate()
                        ?? throw new InvalidOperationException(L.T("NoAudio"));

            var audioPath = Path.Combine(tmp, "audio." + audio.Container.Name);
            await _yt.Videos.Streams.DownloadAsync(audio, audioPath,
                new Progress<double>(x => p.Report(new(L.T("DownloadingAudio"), x * 100))), ct);

            p.Report(new(L.T("ConvertingAudio"), null));
            var wavPath = Path.Combine(tmp, "audio16k.wav");
            await Task.Run(() => AudioConverter.ToWav16k(audioPath, wavPath), ct);

            return await TranscribeWavAsync(wavPath, o.Language, modelPath, p, ct);
        }
        finally
        {
            try { Directory.Delete(tmp, true); } catch { /* best effort */ }
        }
    }

    /// <summary>Transcribes a 16 kHz mono WAV file, reporting progress, an ETA and the text so far.</summary>
    public static async Task<string> TranscribeWavAsync(
        string wavPath, string language, string modelPath, IProgress<ProgressInfo> p, CancellationToken ct)
    {
        var totalSec = AudioTools.WavDurationSeconds(wavPath);

        p.Report(new(L.T("Transcribing"), 0));
        using var factory = WhisperFactory.FromPath(modelPath);
        await using var processor = factory.CreateBuilder()
            .WithLanguage(language) // "auto" = automatic language detection
            .Build();

        var segments = new List<(TimeSpan, TimeSpan, string)>();
        var clock = Stopwatch.StartNew();
        var lastTextReport = TimeSpan.Zero;

        await using var wav = File.OpenRead(wavPath);
        await foreach (var s in processor.ProcessAsync(wav, ct))
        {
            segments.Add((s.Start, s.End, s.Text));

            var pct = totalSec > 0 ? Math.Min(100, s.End.TotalSeconds / totalSec * 100) : (double?)null;
            var status = L.T("Transcribing");
            if (pct is > 1 && clock.Elapsed > TimeSpan.FromSeconds(10))
            {
                var left = TimeSpan.FromSeconds(clock.Elapsed.TotalSeconds * (100 - pct.Value) / pct.Value);
                status = L.T("TranscribingEta", FormatDuration(left));
            }

            // the full text is re-rendered, so update it at most once a second
            string? partial = null;
            if (clock.Elapsed - lastTextReport > TimeSpan.FromSeconds(1))
            {
                partial = FormatParagraphs(segments);
                lastTextReport = clock.Elapsed;
            }
            p.Report(new(status, pct, partial));
        }
        return FormatParagraphs(segments);
    }

    private static string FormatDuration(TimeSpan t) =>
        t.TotalMinutes < 1 ? "< 1 min"
        : t.TotalHours >= 1 ? $"{(int)t.TotalHours} h {t.Minutes:00} min"
        : $"{(int)Math.Ceiling(t.TotalMinutes)} min";

    private static async Task<string> EnsureModelAsync(string model, IProgress<ProgressInfo> p, CancellationToken ct)
    {
        var dir = Path.Combine(AppDir, "models");
        Directory.CreateDirectory(dir);
        var path = Path.Combine(dir, $"ggml-{model}.bin");
        if (File.Exists(path)) return path;

        var url = $"https://huggingface.co/ggerganov/whisper.cpp/resolve/main/ggml-{model}.bin";
        using var resp = await Http.GetAsync(url, HttpCompletionOption.ResponseHeadersRead, ct);
        resp.EnsureSuccessStatusCode();
        var total = resp.Content.Headers.ContentLength;

        var part = path + ".part";
        await using (var src = await resp.Content.ReadAsStreamAsync(ct))
        await using (var dst = File.Create(part))
        {
            var buf = new byte[1 << 20];
            long done = 0;
            int n;
            while ((n = await src.ReadAsync(buf, ct)) > 0)
            {
                await dst.WriteAsync(buf.AsMemory(0, n), ct);
                done += n;
                p.Report(new(L.T("DownloadingModel", model, done / 1_048_576),
                    total > 0 ? done * 100.0 / total : null));
            }
        }
        File.Move(part, path, true);
        return path;
    }

    // ---------- shared: segments -> paragraphs ----------

    private static string FormatParagraphs(IEnumerable<(TimeSpan Start, TimeSpan End, string Text)> segments)
    {
        var sb = new StringBuilder();
        TimeSpan? lastEnd = null;
        foreach (var (start, end, raw) in segments)
        {
            var text = Regex.Replace(raw, @"\s+", " ").Trim();
            if (text.Length == 0) continue;

            if (lastEnd is not null && start - lastEnd > ParagraphGap)
                sb.Append(Environment.NewLine).Append(Environment.NewLine);
            else if (sb.Length > 0)
                sb.Append(' ');

            sb.Append(text);
            lastEnd = end;
        }
        return sb.ToString().Trim();
    }
}
